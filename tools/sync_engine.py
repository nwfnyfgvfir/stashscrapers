"""Deterministically extract the upstream mapping core; run inside Conda.

The supplied checkout must match the requested revision. No network or shell
commands are executed by this tool. Review the generated diff before release.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import os

FILES = ['definition.go', 'mapped.go', 'mapped_config.go', 'mapped_result.go',
         'mapped_postprocessing.go']
DEFAULT_SHA = '47057616fe9da0cf38cfa8c39ab160e5441eeafc'

def extract(source: Path, target: Path, sha: str):
    if not re.fullmatch(r'[0-9a-f]{40}', sha):
        raise ValueError('Expected a full commit SHA')
    target.mkdir(parents=True, exist_ok=True)
    hashes = {}
    for name in FILES:
        raw = (source / 'pkg/scraper' / name).read_text(encoding='utf-8')
        hashes[name] = hashlib.sha256(raw.encode()).hexdigest()
        text = raw.replace('package scraper', 'package engine', 1)
        for pkg in ('logger', 'models', 'sliceutil', 'javascript'):
            text = text.replace(f'github.com/stashapp/stash/pkg/{pkg}',
                                f'stashscrapers/internal/engine/{pkg}')
        if name == 'mapped_postprocessing.go':
            old = 'vm := javascript.NewVM()'
            assert text.count(old) == 1, 'JavaScript patch no longer applies'
            text = text.replace(old, '''vm := javascript.NewVM()
    stop := context.AfterFunc(ctx, func() { vm.Interrupt(ctx.Err()) })
    defer stop()
    vm.SetContext(ctx)''')
        banner = f'// Derived from stashapp/stash {sha}, pkg/scraper/{name}.\n// SPDX-License-Identifier: AGPL-3.0-only\n// Generated by tools/sync_engine.py; local changes are recorded in upstream/PATCHES.md.\n'
        (target / ('upstream_' + name)).write_text(banner + text, encoding='utf-8')
    provenance = {'repository': 'https://github.com/stashapp/stash', 'commit': sha,
                  'license': 'AGPL-3.0', 'files_sha256': hashes}
    Path('upstream').mkdir(parents=True, exist_ok=True)
    Path('upstream/engine-lock.json').write_text(json.dumps(provenance, indent=2) + '\n')
    Path('LICENSE').write_bytes((source / 'LICENSE').read_bytes())
    Path('upstream/STASH-LICENSE').write_bytes((source / 'LICENSE').read_bytes())
    # Preserve the original selector implementations without application routing.
    for name, marker, imports in [
        ('xpath.go', 'var (\n\tmultiSpaceRE', '"context"; "fmt"; "regexp"; "strings"; "github.com/antchfx/htmlquery"; "golang.org/x/net/html"; "stashscrapers/internal/engine/logger"'),
        ('json.go', 'type jsonQuery struct', '"context"; "github.com/tidwall/gjson"; "stashscrapers/internal/engine/logger"'),
    ]:
        raw = (source / 'pkg/scraper' / name).read_text(encoding='utf-8')
        assert marker in raw, f'Selector extraction boundary changed: {name}'
        hashes[name]=hashlib.sha256(raw.encode()).hexdigest()
        body = raw[raw.index(marker):]
        (target / ('upstream_query_' + name)).write_text(
            f'// Derived from stashapp/stash {sha}, pkg/scraper/{name}.\n// SPDX-License-Identifier: AGPL-3.0-only\npackage engine\nimport ({imports})\n' + body, encoding='utf-8')
    subprocess.run(['gofmt','-w',*map(str,sorted(target.glob('upstream_*.go')))],check=True)
    Path('upstream/engine-lock.json').write_text(json.dumps(provenance,indent=2)+'\n')
    adapter=target/'adapter.go'
    if adapter.exists():
        text=adapter.read_text(encoding='utf-8')
        text=re.sub(r'const UpstreamCommit = "[0-9a-f]{40}"',f'const UpstreamCommit = "{sha}"',text)
        text=re.sub(r'const Version = "[^"]+"',f'const Version = "0.1.0+stash.{sha[:7]}"',text)
        adapter.write_text(text,encoding='utf-8')

if __name__ == '__main__':
    if os.environ.get('CONDA_DEFAULT_ENV') != 'stashscrapers':
        raise SystemExit('Run with conda run -n stashscrapers python tools/sync_engine.py')
    p = argparse.ArgumentParser()
    p.add_argument('--source', required=True, type=Path)
    p.add_argument('--sha', default=DEFAULT_SHA)
    a = p.parse_args()
    extract(a.source, Path('internal/engine'), a.sha)
